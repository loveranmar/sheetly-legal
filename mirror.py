#!/usr/bin/env python3
"""Regenerate the privacy and terms mirrors from the trysheetly.com source pages.

The canonical pages are site/privacy.html and site/terms.html (repo loveranmar/sheetly-site,
served at www.trysheetly.com). This repo only mirrors them for the GitHub Pages URLs that old
app builds and old App Store listings still carry. Never edit the policy text here by hand.

Usage:  python3 mirror.py [path/to/site]        (default: ../site)

What it does, per page: takes the site's article (from the lede to </article>), and puts it in
place of this mirror's body (from the lede to <footer>), keeping this mirror's own head, banner,
title, chips and footer. On the way it:
  - turns the site's "doc-note" boxes into this page's "note" boxes ("Summary" -> "In plain English"),
  - makes every root-relative or #fragment link absolute on www.trysheetly.com,
  - keeps this mirror's own link cards in place of the site's "See also" line,
  - copies the "Last updated" date into the chip.
support.html has its own layout here and is not regenerated by this script.
"""
import os
import re
import sys

HOST = 'https://www.trysheetly.com'
PAGES = ['privacy', 'terms']

here = os.path.dirname(os.path.abspath(__file__))
site = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'site'))


def absolute(html, page):
    html = re.sub(r'href="#([^"]*)"', lambda m: 'href="%s/%s#%s"' % (HOST, page, m.group(1)), html)
    html = re.sub(r'href="/([^"]*)"', lambda m: 'href="%s/%s"' % (HOST, m.group(1)), html)
    return html


for page in PAGES:
    src = open(os.path.join(site, page + '.html'), encoding='utf-8').read()
    dst_path = os.path.join(here, page + '.html')
    dst = open(dst_path, encoding='utf-8').read()

    updated = re.search(r'<p class="doc-updated">Last updated ([^<]+)</p>', src).group(1).strip()
    art = src[src.index('      <p class="doc-lede">'):src.index('    </article>')].rstrip() + '\n'

    art = art.replace('<div class="doc-note">', '<div class="note">')
    art = art.replace('<div class="doc-note-title">Summary</div>', '<div class="note-title">In plain English</div>')
    art = art.replace('<div class="doc-note-title">', '<div class="note-title">')
    art = absolute(art, page)

    cards = re.search(r'        <div class="doc-links">.*?\n        </div>\n', dst, re.S).group(0)
    see_also = re.compile(r'        <p>See also the .*?</p>\n')
    assert len(see_also.findall(art)) == 1, page + ': expected one "See also" line in the site page'
    art = see_also.sub(lambda m: cards, art)

    start = dst.index('      <p class="doc-lede">')
    end = dst.index('  <footer>')
    out = dst[:start] + art + '\n' + dst[end:]
    out, n = re.subn(r'<span class="chip">Last updated · [^<]*</span>',
                     '<span class="chip">Last updated · %s</span>' % updated, out)
    assert n == 1, page + ': no "Last updated" chip'

    leftover = re.findall(r'href="(?:/|#)[^"]*"', out)
    assert not leftover, (page, leftover)
    if out != dst:
        open(dst_path, 'w', encoding='utf-8').write(out)
    print('%s.html: %s (last updated %s)' % (page, 'updated' if out != dst else 'unchanged', updated))
